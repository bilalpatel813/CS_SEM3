package JAVA_practical.pract4;
import java.util.*;

public class Hash {
    public static void main(String[] args) {
        Set<String> names = new HashSet<>();
        names.add("Adnan");
        names.add("Bilal");
        names.add("Raza");
    

    for (String name : names){
        System.out.println(name);
    }
}
}
